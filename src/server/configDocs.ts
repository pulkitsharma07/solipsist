/** The documentation of the settings, written from the TABLE (`config/table.ts`, its rows in `config/*Rows.ts`): `CONFIGURATION.md` and `solipsist.example.yaml`. */
import { describeKind, ENV_ONLY, GROUPS, TABLE, type Setting } from "./config";

export const START = "<!-- config:start (generated by `bun scripts/config-docs.ts`; edit the rows in src/server/config/ instead) -->";
export const END = "<!-- config:end -->";

const groupOf = (s: Setting) => (s.key.includes(".") ? s.key.split(".")[0]! : "pages");
const leaf = (s: Setting) => s.key.split(".").at(-1)!;

const scalar = (v: unknown) => (typeof v === "string" && /^[~.\w/-]+$/.test(v) && !/^(true|false|null|off|on|yes|no|\d.*)$/i.test(v) ? v : JSON.stringify(v));

/** A value as the lines after `key:`; a list is a block list under it. */
function yamlValue(v: unknown, pad: string): { inline: string; block: string[] } {
  if (Array.isArray(v)) return { inline: "", block: v.map((x) => `${pad}  - ${scalar(x)}`) };
  return { inline: ` ${scalar(v)}`, block: [] };
}

const wrap = (text: string, width: number): string[] => {
  const out: string[] = [];
  let line = "";
  for (const w of text.split(/\s+/)) {
    if (line && line.length + 1 + w.length > width) { out.push(line); line = w; } else line = line ? `${line} ${w}` : w;
  }
  if (line) out.push(line);
  return out;
};

/** `solipsist.example.yaml`: every key with its default and its summary; an optional setting is commented out. */
export function renderExample(): string {
  const lines = [
    "# Solipsist settings. Copy this file to `solipsist.yaml` (next to where you start the server) or to",
    "# `~/.config/solipsist/config.yaml`, and keep only what you change. Every key is shown with its default.",
    "# The environment wins over this file: each setting names its variable. Reference: CONFIGURATION.md.",
    "",
  ];
  for (const g of GROUPS) {
    const rows = TABLE.filter((s) => groupOf(s) === g.id);
    const nested = g.id !== "pages";
    if (nested) lines.push(`${g.id}:`);
    for (const s of rows) {
      const pad = nested ? "  " : "";
      for (const l of wrap(`${s.summary} Env: ${s.env}.`, 112 - pad.length)) lines.push(`${pad}# ${l}`);
      const optional = s.default === undefined;
      const { inline, block } = yamlValue(optional ? s.example : s.default, pad);
      const mark = optional ? "# " : "";
      lines.push(`${pad}${mark}${leaf(s)}:${inline}`);
      for (const b of block) lines.push(`${pad}${mark}${b.slice(pad.length)}`);
    }
    lines.push("");
  }
  return lines.join("\n").replace(/\n+$/, "\n");
}

const shownDefault = (s: Setting): string => {
  if (s.default === undefined) return "unset";
  if (Array.isArray(s.default)) return s.default.map((x) => `\`${x}\``).join(", ");
  return `\`${String(s.default)}\``;
};

/** The reference: one section per group, each setting with its type, default, env name and purpose. */
export function renderReference(): string {
  const out: string[] = [];
  for (const g of GROUPS) {
    out.push(`### ${g.title}`, "", g.intro, "");
    for (const s of TABLE.filter((x) => groupOf(x) === g.id)) {
      out.push(`#### \`${s.key}\``, "", s.summary + (s.secret ? " **A secret.**" : ""), "");
      out.push("| Type | Default | Environment |", "|---|---|---|", `| ${describeKind(s)} | ${shownDefault(s)} | \`${s.env}\` |`, "");
      out.push(s.purpose, "");
    }
  }
  out.push("### Variables that are not settings", "", "These are read as plain environment variables, outside the settings table.", "");
  out.push("| Variable | Why |", "|---|---|", ...ENV_ONLY.map((e) => `| \`${e.name}\` | ${e.why} |`), "");
  return out.join("\n");
}

/** `CONFIGURATION.md` with its generated part replaced. */
export function spliceReference(doc: string): string {
  const a = doc.indexOf(START);
  const b = doc.indexOf(END);
  if (a < 0 || b < a) throw new Error("CONFIGURATION.md: the config:start / config:end markers are missing");
  return `${doc.slice(0, a)}${START}\n\n${renderReference()}\n${doc.slice(b)}`;
}
